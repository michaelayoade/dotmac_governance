    def connector_report(
        self,
        *,
        runtime: str = QUIET_RUNTIME,
        router: str = QUIET_ROUTER,
        owner: str = "def decide() -> bool:\n    return True\n",
        test_source: str = "def test_drift() -> None:\n    assert True\n",
        surface: dict[str, object] | None = None,
        extra: Mapping[str, str] | None = None,
        untracked: Mapping[str, str] | None = None,
    ) -> ConformanceReport:
        value = profile()
        value["external_connector_surface"] = surface or connector_surface()
        return self.evaluate(
            value,
            runtime=runtime,
            router=router,
            owner=owner,
            test_source=test_source,
            extra=extra,
            untracked=untracked,
        )

    def excluded_paths(self, report: ConformanceReport) -> set[str]:
        return {
            item.path.as_posix()
            for item in report.diagnostics
            if item.code is DiagnosticCode.CONNECTOR_SCOPE_EXCLUDED
        }

    def exceeded_categories(self, report: ConformanceReport) -> set[str]:
        """Categories the ratchet reported above baseline, by name.

        The message is parsed rather than the diagnostic counted, so a proof can
        assert that a planted surface fires its OWN category and no other.
        """
        return {
            item.message.split(":", 1)[0]
            for item in report.diagnostics
            if item.code is DiagnosticCode.CONNECTOR_BASELINE_EXCEEDED
        }

    def with_exclusion(self, exclusion: object) -> dict[str, object]:
        surface = connector_surface()
        surface["exclusions"] = [exclusion]
        return surface

    def conserved_records(self, report: ConformanceReport) -> list[dict[str, object]]:
        """The conserved findings the engine published, as profile entries.

        The notice carries the exact JSON object a reviewer transcribes into
        `conserved_exclusions`, so the ledger is regenerated from a run rather
        than hand-assembled — and a test that reads it is asserting the
        published record is the one the parser accepts.
        """
        records: list[dict[str, object]] = []
        for item in report.diagnostics:
            if item.code is not DiagnosticCode.CONNECTOR_CONSERVED_RECORDED:
                continue
            payload = json.loads(item.message[item.message.index("{") :])
            assert isinstance(payload, dict)
            records.append(payload)
        return records

    def conserved_codes(self, report: ConformanceReport) -> set[DiagnosticCode]:
        return {
            item.code
            for item in report.diagnostics
            if item.code.value.startswith("connector.conserved.")
        }

    def surface_with(self, records: list[dict[str, object]]) -> dict[str, object]:
        surface = connector_surface()
        surface["conserved_exclusions"] = records
        return surface

    def conserved_ledger_report(
        self,
        *,
        runtime: str = QUIET_RUNTIME,
        test_source: str = "def test_drift() -> None:\n    assert True\n",
        extra: Mapping[str, str] | None = None,
    ) -> tuple[ConformanceReport, list[dict[str, object]], ConformanceReport]:
        """Run twice: once with an empty ledger, once with the published one.

        The pair is the whole property. The first run must NAME what left the
        universe; the second must accept exactly that and nothing more.
        """
        first = self.connector_report(
            runtime=runtime, test_source=test_source, extra=extra
        )
        records = self.conserved_records(first)
        second = self.connector_report(
            surface=self.surface_with(records),
            runtime=runtime,
            test_source=test_source,
            extra=extra,
        )
        return first, records, second

    def test_every_connector_category_fires_on_a_planted_surface(self) -> None:
        """ADR 0018 sensitivity proof, one per category, in the firing
        direction: a planted surface must raise its own category alone."""
        for category, planted, _ in CONNECTOR_PROOFS:
            for index, source in enumerate(planted):
                with self.subTest(category=category, planted=index):
                    report = self.connector_report(runtime=source)
                    self.assertEqual(
                        self.exceeded_categories(report),
                        {category},
                        report.to_dict(),
                    )

    def test_every_connector_category_stays_quiet_on_a_look_alike(self) -> None:
        """The other direction of the same proof: a plausible look-alike must
        not be counted. A detector that only ever fires is not evidence."""
