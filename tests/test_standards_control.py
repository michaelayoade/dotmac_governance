    # -- Exclusion conservation (ADR 0011, schema 8) ------------------------
    #
    # An exclusion was a silent subtraction: nothing recorded what left the
    # universe, so an unsound classifier could remove a live connector and the
    # only trace was a notice indistinguishable from every other notice. Only
    # CONNECTOR-SHAPED test-only findings are conserved; a test file holding no
    # connector surface records nothing, because recording every test file
    # drowns the signal.

    def test_the_blessed_double_is_conserved_with_its_fingerprint(self) -> None:
        """Conservation proof 1. The legitimate transitive test double stays
        EXCLUDED and is RECORDED, path, symbol, category and fingerprint.

        Being excluded is not the claim under test — that already worked. The
        claim is that the subtraction is now named, and that the name the
        engine publishes is exactly what the ledger accepts.
        """
        first, records, second = self.conserved_ledger_report(
            test_source=TEST_IMPORTING_THE_DOUBLE,
            extra={"example/doubles.py": PROVIDER_DOUBLE},
        )
        self.assertIn("example/doubles.py", self.excluded_paths(first))
        self.assertEqual(len(records), 1, records)
        record = records[0]
        self.assertEqual(record["path"], "example/doubles.py")
        self.assertEqual(record["symbol"], "provider")
        self.assertEqual(record["category"], "outbound_transport")
        fingerprint = record["fingerprint"]
        assert isinstance(fingerprint, str)
        self.assertRegex(fingerprint, r"^[0-9a-f]{64}$")
        # Declaring it is an acknowledgement, not a waiver: the file is still
        # out of the universe because the DERIVATION put it there.
        self.assertFalse(first.conforms, first.to_dict())
        self.assertTrue(second.conforms, second.to_dict())
        self.assertIn("example/doubles.py", self.excluded_paths(second))

