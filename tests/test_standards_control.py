# --- A client that is CAUGHT is not a client that is CALLED ----------------
# `outbound_transport` asked two questions: is a client library imported, and is
# anything named `get`/`post`/... called. Neither reads the receiver, so a
# module that delegates every outbound call to another service and imports the
# library ONLY to name its exception classes scores the surface off its own
# `payload.get(...)` accessors.
#
# Two real modules, both the same shape:
# `crm-guardrails/app/services/crm/conversations/comments.py` (33 request-named
# calls, all of them `dict.get`; the single `httpx` reference is
# `except httpx.HTTPStatusError`) and `sub-adopt/app/tasks/notifications.py`
# (three `except (httpx.TimeoutException, httpx.NetworkError)` clauses; the
# requests are made by `meta_pages`, which is measured on its own account).
#
# An `except` clause's exception type is the ONE position where naming a
# client commits to nothing. Annotations are NOT in that set, and the boundary
# was found by proof: excluding them too reads like the same idea, but an
# annotated PARAMETER is how an already-constructed client is handed in, and
# three fixtures above (`PLANTED_DELIVERY_RETRY`, `CONFIG_MAPPING_RETRY`,
# `DECORATED_RETRY`) are that shape. `INJECTED_CLIENT_CALLED` below pins it.

#: The false positive. Every `.get` is a mapping accessor.
